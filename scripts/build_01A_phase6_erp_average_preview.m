%% Build the synchronized primary averaging copy

PRIMARY_AVERAGE_READY = PRIMARY_CORRECT;

epochFlags = zeros(1,300,'uint16');
for ep = 1:300
    epochFlags(ep) = uint16( ...
        PRIMARY_AVERAGE_READY.epoch(ep).eventflag);
end

artifactMask = bitget(epochFlags,1) == 1;
incorrectMask = bitget(epochFlags,2) == 1;
combinedRejectMask = artifactMask | incorrectMask;
primaryGoodMask = ~combinedRejectMask;
sensitivityGoodMask = ~artifactMask;

assert(sum(artifactMask) == 5);
assert(sum(incorrectMask) == 142);
assert(sum(artifactMask & incorrectMask) == 1);
assert(sum(primaryGoodMask) == 154);
assert(sum(sensitivityGoodMask) == 295);

% ERPLAB's synchronization gate treats rejmanual as the total rejection
% mask. Bit 1/bit 2 and the separate rejbehavior field retain the reasons.
PRIMARY_AVERAGE_READY.reject.rejmanual = ...
    combinedRejectMask;
PRIMARY_AVERAGE_READY.setname = ...
    '01A_m1ref_target_epochs_primary_average_ready';
PRIMARY_AVERAGE_READY.etc.behavior_rejection.rejmanual_role = ...
    'union of flag bit 1 artifact and flag bit 2 incorrect';

assert(isequal(logical( ...
    PRIMARY_AVERAGE_READY.reject.rejmanual(:))', ...
    combinedRejectMask));
assert(isequal(find( ...
    PRIMARY_AVERAGE_READY.reject.rejbehavior), ...
    find(incorrectMask)));

%% Extract one bin number per epoch for independent reconstruction

epochBin = nan(1,300);
for ep = 1:300
    binValue = PRIMARY_AVERAGE_READY.epoch(ep).eventbini;
    if iscell(binValue)
        binValue = binValue{1};
    end
    binValue = double(binValue);
    binValue = binValue( ...
        binValue >= 1 & binValue <= 10);
    assert(numel(binValue) == 1, ...
        'Expected one valid bin per epoch.');
    epochBin(ep) = binValue;
end

expectedPrimaryAccepted = ...
    [8 10 21 18 28 4 4 16 23 22];
expectedSensitivityAccepted = ...
    [29 30 30 29 29 29 30 30 30 29];

for b = 1:10
    assert(sum(primaryGoodMask & ...
        epochBin == b) == ...
        expectedPrimaryAccepted(b));
    assert(sum(sensitivityGoodMask & ...
        epochBin == b) == ...
        expectedSensitivityAccepted(b));
end

%% Average with the installed ERPLAB implementation

