%% Independently reconstruct averages and SEM

primaryAverageError = 0;
primarySEMError = 0;
sensitivityAverageError = 0;
sensitivitySEMError = 0;

for b = 1:10
    primaryEpochs = find( ...
        primaryGoodMask & epochBin == b);
    sensitivityEpochs = find( ...
        sensitivityGoodMask & epochBin == b);

    primaryData = double( ...
        PRIMARY_AVERAGE_READY.data( ...
        :,:,primaryEpochs));
    sensitivityData = double( ...
        PRIMARY_FINAL.data( ...
        :,:,sensitivityEpochs));

    reconstructedPrimary = mean( ...
        primaryData,3);
    reconstructedSensitivity = mean( ...
        sensitivityData,3);
    reconstructedPrimarySEM = std( ...
        primaryData,0,3) / ...
        sqrt(numel(primaryEpochs));
    reconstructedSensitivitySEM = std( ...
        sensitivityData,0,3) / ...
        sqrt(numel(sensitivityEpochs));

    erplabPrimary = double( ...
        ERP_PRIMARY_PREVIEW.bindata(:,:,b));
    erplabSensitivity = double( ...
        ERP_SENSITIVITY_PREVIEW.bindata(:,:,b));
    erplabPrimarySEM = double( ...
        ERP_PRIMARY_PREVIEW.binerror(:,:,b));
    erplabSensitivitySEM = double( ...
        ERP_SENSITIVITY_PREVIEW.binerror(:,:,b));

    primaryAverageError = max( ...
        primaryAverageError, ...
        max(abs(reconstructedPrimary(:) - ...
        erplabPrimary(:))));
    sensitivityAverageError = max( ...
        sensitivityAverageError, ...
        max(abs(reconstructedSensitivity(:) - ...
        erplabSensitivity(:))));
    primarySEMError = max( ...
        primarySEMError, ...
        max(abs(reconstructedPrimarySEM(:) - ...
        erplabPrimarySEM(:))));
    sensitivitySEMError = max( ...
        sensitivitySEMError, ...
        max(abs(reconstructedSensitivitySEM(:) - ...
        erplabSensitivitySEM(:))));
end

assert(primaryAverageError < 1e-4);
assert(sensitivityAverageError < 1e-4);
assert(primarySEMError < 1e-4);
assert(sensitivitySEMError < 1e-4);

