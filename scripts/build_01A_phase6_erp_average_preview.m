ERP_SENSITIVITY_PREVIEW = pop_averager( ...
    PRIMARY_FINAL, ...
    'Criterion','good', ...
    'ExcludeBoundary','on', ...
    'SEM','on', ...
    'Warning','off', ...
    'DQ_flag',1);

ERP_SENSITIVITY_PREVIEW.erpname = ...
    '01A_m1ref_erp_sensitivity_all_clean_preview';

%% Structural and count QC

assert(ERP_PRIMARY_PREVIEW.nchan == 67);
assert(ERP_PRIMARY_PREVIEW.pnts == 250);
